// Bundles the shared formula engine (packages/contract/src/sheetEngine.ts)
// for the API, which runs it to give agents worked-out sheet values.
// Run with `make gen-sheet-engine`; sheet-template-display.test.mjs fails
// when the bundle is out of date.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(new URL("../apps/web/package.json", import.meta.url));
const esbuild = require("esbuild");

export async function bundleSheetEngine() {
  const result = await esbuild.build({
    entryPoints: [new URL("../packages/contract/src/sheetEngine.ts", import.meta.url).pathname],
    absWorkingDir: new URL("..", import.meta.url).pathname,
    bundle: true,
    format: "iife",
    globalName: "SheetEngine",
    target: "es2017",
    charset: "utf8",
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  return `// Generated by make gen-sheet-engine from packages/contract/src/sheetEngine.ts. Do not edit.\n${result.outputFiles[0].text}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = new URL("../apps/api/internal/features/sheet/engine/sheet-engine.js", import.meta.url);
  writeFileSync(file, await bundleSheetEngine());
  console.log(`wrote ${file.pathname}`);
}
