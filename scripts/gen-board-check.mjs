// Bundles the described-card check (packages/contract/src/boardCheck.ts) for
// the API, whose Describe AI draws its draft cards with it before answering.
// Run with `make gen-board-check`; genui.test.mjs fails when the bundle is
// out of date. Minified: zod and the OpenUI parser come to 850 KB otherwise.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(new URL("../apps/web/package.json", import.meta.url));
const esbuild = require("esbuild");

export async function bundleBoardCheck() {
  const result = await esbuild.build({
    entryPoints: [new URL("../packages/contract/src/boardCheck.ts", import.meta.url).pathname],
    absWorkingDir: new URL("..", import.meta.url).pathname,
    bundle: true,
    format: "iife",
    globalName: "BoardCheck",
    target: "es2017",
    charset: "utf8",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  return `// Generated by make gen-board-check from packages/contract/src/boardCheck.ts. Do not edit.\n${result.outputFiles[0].text}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = new URL("../apps/api/internal/features/provider/board/board-check.js", import.meta.url);
  writeFileSync(file, await bundleBoardCheck());
  console.log(`wrote ${file.pathname}`);
}
