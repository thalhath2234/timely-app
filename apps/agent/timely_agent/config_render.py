"""Hermes config files for Timely's agent (plan section 6.3). Python owns the shape, Go owns the values.

Three layers:

1. **Managed** (``<agent>/managed/config.yaml`` = ``HERMES_MANAGED_DIR``): host-wide floors,
   written by ``boot.py prepare`` at API start and read back through Hermes' own loader as a
   canary. Hermes deep-merges it on top of every account config (``managed_scope``), so an
   account cannot loosen it through ``load_config()``.
2. **Account** (``<home>/config.yaml``): rendered from the settings JSON Go sends before each
   spawn. It repeats the managed floors, because some Hermes readers take ``config.yaml`` raw
   and never apply the managed overlay (``agent.skill_utils._load_raw_config``, which reads
   ``skills.external_dirs`` and ``skills.disabled``). Its sha256 is the ``settings_hash`` of
   ``hello``; the worker refuses a home whose file no longer matches.
3. **Per run**: model credentials, toolsets and flags arrive in ``run.start``.

Files are written as JSON, which is valid YAML 1.2 and keeps the renderer stdlib-only and the
hash stable. Hermes parses them with its YAML loader (the canary proves it).
"""

from __future__ import annotations

import copy
import functools
import hashlib
import ipaddress
import json
import os
import re
from pathlib import Path
from typing import Any, Mapping
from urllib.parse import urlsplit

TIMELY_PLUGINS = ("timely_gate", "timely_tools", "timely_learning", "timely_bot")

HEADER = "# Generated by Timely (apps/agent/timely_agent/config_render.py). Do not edit: it is re-rendered.\n"

# Toolsets no Timely run ever gets (decision 6 and section 8.1); also pinned as disabled.
NEVER_TOOLSETS = (
    "cronjob", "kanban", "discord", "discord_admin", "feishu_doc", "feishu_drive", "desktop_ui",
    "catalog", "project", "onboarding", "connections", "computer_use", "browser",
    "hermes-yuanbao", "google_meet",
)


# Bundled plugin folders Timely never loads besides the messaging platforms (section 8.3): media
# generation (no media surface, section 8.1) and Hermes' own web dashboard sign-in.
DISABLED_PLUGIN_GROUPS = ("image_gen", "video_gen", "dashboard_auth")
_KIND = re.compile(r"^kind:\s*['\"]?([A-Za-z_-]+)", re.MULTILINE)


@functools.lru_cache(maxsize=1)
def disabled_bundled_plugins() -> tuple[str, ...]:
    """Bundled plugin keys pinned in ``plugins.disabled``: every ``kind: platform`` manifest
    (messaging adapters and a2a, decision 6) and the groups in ``DISABLED_PLUGIN_GROUPS``.

    Hermes auto-loads bundled backends and registers bundled platforms lazily whatever
    ``plugins.enabled`` says (``hermes_cli/plugins_discovery.py`` ``gate_manifest``); only
    ``plugins.disabled`` wins over that. Read from the snapshot's manifests, so a platform added
    upstream is disabled by the next sync without a code change.
    """
    from timely_agent import paths

    root = paths.hermes_dir() / "plugins"
    keys: set[str] = set()
    for manifest in sorted(root.glob("*/plugin.yaml")) + sorted(root.glob("*/*/plugin.yaml")):
        rel = manifest.parent.relative_to(root).as_posix()
        try:
            kind = _KIND.search(manifest.read_text(encoding="utf-8"))
        except OSError:
            continue
        if (kind and kind.group(1) == "platform") or rel.split("/", 1)[0] in DISABLED_PLUGIN_GROUPS:
            keys.add(rel)
    return tuple(sorted(keys))


def managed_floors(*, timely_skills_dir: os.PathLike | str | None,
                   browser_executable: str = "") -> dict[str, Any]:
    """The host-wide floors (section 6.3) with the keys Hermes v0.23.0 actually reads."""
    floors: dict[str, Any] = {
        "plugins": {
            "enabled": list(TIMELY_PLUGINS),
            "disabled": list(disabled_bundled_plugins()),
            "isolation": "in_process",
            "auto_apply": False,
            "auto_update_check_hours": 0,
            # The cronjob_manage shim (section 7.10); no other plugin may override a built-in.
            "entries": {"timely_bot": {"allow_tool_override": True}},
        },
        "security": {
            # Hermes' SSRF guard blocks private, loopback and CGNAT/Tailscale ranges only with these.
            "allow_private_urls": False,
            "fake_ip_ranges": [],
            "allow_lazy_installs": False,
            "redact_secrets": True,
            "protected_instruction_files": True,
        },
        "telemetry": {"shared_metrics": {"enabled": False, "send": False}},
        "approvals": {
            "mode": "manual",
            "cron_mode": "deny",
            "unattended_mode": "deny",
            "single_query_mode": "deny",
        },
        "skills": {
            "inline_shell": False,
            "guard_agent_created": True,
            "project_discovery": False,
            "trusted_project_dirs": [],
            "external_dirs": [str(timely_skills_dir)] if timely_skills_dir else [],
            "create_dir": "",
        },
        "web": {"keyless_fallback": False, "keyless_rescue": False},
        # auto_local_for_private_urls would hand a private URL to a local Chromium even with a
        # cloud provider set; the local backend itself ignores allow_private_urls, so timely_gate
        # also refuses private URL literals in browser tool arguments (plan 12, residual in 14).
        "browser": {"use_real_profile": False, "executable_path": browser_executable or "",
                    "auto_local_for_private_urls": False},
        # Hermes' LSP layer would `go install` / `npm install` a missing language server on the
        # first write_file of a matching file; manual = use only binaries already on PATH. The
        # install guard (R1) also replaces the installer.
        "lsp": {"install_strategy": "manual"},
        "memory": {"provider": ""},
        "display": {"language": "en"},
        "auth": {"adopt_external_logins": False},
        "cron": {"allow_agent_scheduling": False},
        "hooks_auto_accept": False,
        "tools": {"tool_search": {"enabled": "off"}, "connectors": {"enabled": False}},
        "agent": {"disabled_toolsets": list(NEVER_TOOLSETS)},
        # Timely names its own chats: no background title call to the account's model after the
        # first turn (an extra billed request that also raced the contract tests' request counts).
        "auxiliary": {"title_generation": {"enabled": False}},
    }
    return floors


def floor_leaves(floors: Mapping, prefix: str = "") -> dict[str, Any]:
    """Every leaf of a floors dict as ``{"dotted.key": value}``. A non-empty mapping is walked;
    anything else (scalars, lists, empty mappings) is a leaf."""
    out: dict[str, Any] = {}
    for key, value in floors.items():
        dotted = f"{prefix}{key}"
        if isinstance(value, Mapping) and value:
            out.update(floor_leaves(value, dotted + "."))
        else:
            out[dotted] = value
    return out


# The canary checks every leaf of the managed floors after Hermes loaded the files, so a
# hand-edited managed/config.yaml cannot loosen a floor that is not read back. Path-valued ones
# are compared against the layout and prepare's inputs, so a hand-edited managed file cannot
# pass by agreeing with itself.
def canary_keys() -> tuple[str, ...]:
    return tuple(floor_leaves(managed_floors(timely_skills_dir=None)))


def deep_merge(base: dict, top: Mapping) -> dict:
    out = copy.deepcopy(base)
    for k, v in top.items():
        if isinstance(v, Mapping) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def get_dotted(cfg: Mapping, dotted: str, default: Any = None) -> Any:
    cur: Any = cfg
    for part in dotted.split("."):
        if not isinstance(cur, Mapping) or part not in cur:
            return default
        cur = cur[part]
    return cur


def dumps(cfg: Mapping) -> bytes:
    return (HEADER + json.dumps(cfg, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def sha256_file(path: os.PathLike | str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_atomic(path: os.PathLike | str, data: bytes, mode: int = 0o600) -> str:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with open(tmp, "wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    try:
        os.chmod(tmp, mode)
    except OSError:
        pass
    os.replace(tmp, path)
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------- MCP entries (sections 6.3, 8.2)

def mcp_entry_hash(entry: Mapping) -> str:
    """sha256 of the entry's canonical JSON (sorted keys, no spaces); Go stores it on approval."""
    return hashlib.sha256(json.dumps(entry, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def private_mcp_url(url: str) -> bool:
    """True for a URL whose host is a literal private, loopback, link-local or CGNAT address
    (or ``localhost``). Go also resolves names before each render; this is the literal check."""
    try:
        host = urlsplit(url).hostname or ""
    except ValueError:
        return True
    if not host:
        return True
    if host.lower() in ("localhost", "localhost.localdomain") or host.lower().endswith(".localhost"):
        return True
    try:
        ip = ipaddress.ip_address(host)
    except ValueError:
        return False
    cgnat = ipaddress.ip_network("100.64.0.0/10")
    return (ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved or ip.is_unspecified
            or ip.is_multicast or (ip.version == 4 and ip in cgnat))


def filter_mcp_servers(servers: Mapping | None, *, host_allowed: bool,
                       approved_hashes: list[str] | tuple[str, ...]) -> tuple[dict, list[str]]:
    """``(kept, dropped_reasons)``. Stdio (``command``) servers only for a host-allowed account
    and only with an approved entry hash; URL servers must not point at a private address."""
    kept: dict[str, Any] = {}
    dropped: list[str] = []
    approved = set(approved_hashes or ())
    for name, entry in (servers or {}).items():
        if not isinstance(entry, Mapping):
            dropped.append(f"{name}: entry is not a mapping")
            continue
        if entry.get("command"):
            if not host_allowed:
                dropped.append(f"{name}: command servers need a host-allowed account")
                continue
            if mcp_entry_hash(entry) not in approved:
                dropped.append(f"{name}: command server was not approved on a host card")
                continue
        elif entry.get("url"):
            if private_mcp_url(str(entry["url"])):
                dropped.append(f"{name}: URL points at a private, loopback or CGNAT address")
                continue
        else:
            dropped.append(f"{name}: needs url or command")
            continue
        kept[str(name)] = dict(entry)
    return kept, dropped


# ---------------------------------------------------------------- renderers

def render_managed(layout, *, timely_skills_dir, browser_executable: str = "") -> tuple[Path, str]:
    floors = managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable)
    path = layout.managed_config
    return path, write_atomic(path, dumps(floors), mode=0o644)


ACCOUNT_STATE = ".timely-account.json"  # what render-account decided; the self-test reads it

SOUL_TEXT = """You are Timely's assistant, the agent inside the Timely app. You help the person who
signed in plan their tasks, events, documents and habits. You present yourself as Timely.
"""


def account_config(settings: Mapping, *, timely_skills_dir, browser_executable: str = "",
                   workspace: os.PathLike | str | None = None) -> tuple[dict, list[str]]:
    """The account ``config.yaml`` content and the list of dropped MCP entries.

    ``terminal.cwd`` and ``terminal.home_mode`` matter: each run binds Hermes' per-turn terminal
    policy from this file (``run_chat``), and a bound policy ignores ``TERMINAL_*`` in the
    process environment."""
    settings = dict(settings or {})
    cfg: dict[str, Any] = {}
    model = settings.get("model")
    if isinstance(model, Mapping) and model:
        cfg["model"] = {k: v for k, v in model.items() if k in ("default", "provider", "base_url", "api_mode")}
    cfg["toolsets"] = [str(t) for t in settings.get("toolsets") or [] if str(t) not in NEVER_TOOLSETS]
    learning = settings.get("learning") if isinstance(settings.get("learning"), Mapping) else {}
    cfg["memory"] = {
        "memory_enabled": bool(learning.get("memory", False)),
        "user_profile_enabled": bool(learning.get("user_profile", False)),
        "write_approval": True,
    }
    cfg["skills"] = {
        "disabled": sorted({str(s) for s in settings.get("skills_disabled") or []}),
        "write_approval": True,
    }
    cfg["curator"] = {"enabled": bool(settings.get("curator", False)), "consolidate": False}
    if settings.get("timezone"):
        cfg["timezone"] = str(settings["timezone"])
    timeout = settings.get("approval_timeout_s")
    cfg["approvals"] = {"timeout": int(timeout) if isinstance(timeout, (int, float)) and timeout > 0 else 600}
    cfg["terminal"] = {"backend": "local", "home_mode": str(settings.get("terminal_home_mode") or "profile")}
    if workspace:
        cfg["terminal"]["cwd"] = str(workspace)
    servers, dropped = filter_mcp_servers(
        settings.get("mcp_servers"), host_allowed=bool(settings.get("host_allowed")),
        approved_hashes=list(settings.get("approved_mcp_hashes") or []))
    cfg["mcp_servers"] = servers
    floors = managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable)
    return deep_merge(cfg, floors), dropped


def render_account(layout, account: str, settings: Mapping, *, timely_skills_dir,
                   browser_executable: str = "") -> dict[str, Any]:
    """Create the account home, write ``config.yaml`` and ``SOUL.md``; returns what Go needs."""
    home = layout.ensure_home(account)
    cfg, dropped = account_config(settings, timely_skills_dir=timely_skills_dir,
                                  browser_executable=browser_executable, workspace=home / "workspace")
    config_sha = write_atomic(home / "config.yaml", dumps(cfg))
    account_state = {"host_allowed": bool(settings.get("host_allowed")),
                     "approved_mcp_hashes": sorted({str(h) for h in settings.get("approved_mcp_hashes") or []}),
                     "config_sha256": config_sha}
    write_atomic(home / ACCOUNT_STATE, (json.dumps(account_state, indent=2, sort_keys=True) + "\n").encode())
    soul = settings.get("soul") if isinstance(settings.get("soul"), str) and settings.get("soul") else SOUL_TEXT
    write_atomic(home / "SOUL.md", soul.encode("utf-8"))
    return {"home": str(home), "config_sha256": config_sha, "mcp_dropped": dropped}


# ---------------------------------------------------------------- canary (needs Hermes imported)

def expected_canary(timely_skills_dir, browser_executable: str = "") -> dict[str, Any]:
    return floor_leaves(managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable))


def _norm(key: str, value: Any) -> Any:
    if key == "skills.external_dirs" and isinstance(value, list):
        return [str(Path(os.path.expandvars(os.path.expanduser(str(v)))).resolve()) for v in value]
    return value


def canary(timely_skills_dir, browser_executable: str = "") -> list[str]:
    """Read the managed and effective config back through Hermes; returns the mismatches.

    Every leaf of ``managed_floors`` is compared (``floor_leaves``), with the values ``prepare``
    used (``timely_skills_dir``, ``browser_executable``), so an edit to the shared managed file
    between API start and a spawn fails the self-test whatever key it loosens.

    Checks three readers: the managed file alone (``managed_scope.load_managed_config``), the
    merged config every ``load_config()`` caller sees, and the raw reader skill discovery uses
    (``agent.skill_utils.get_external_skills_dirs``).
    """
    from hermes_cli import managed_scope
    from hermes_cli.config import load_config

    managed_scope.invalidate_managed_cache()
    problems: list[str] = []
    if managed_scope.get_managed_dir() is None:
        return ["HERMES_MANAGED_DIR is not a folder Hermes accepts"]
    managed = managed_scope.load_managed_config()
    if not managed:
        return ["Hermes could not read the managed config (missing or malformed)"]
    effective = load_config()
    for key, want in expected_canary(timely_skills_dir, browser_executable).items():
        want_n = _norm(key, want)
        got_m = _norm(key, get_dotted(managed, key))
        got_e = _norm(key, get_dotted(effective, key))
        if got_m != want_n:
            problems.append(f"managed {key} = {got_m!r}, want {want_n!r}")
        if got_e != want_n:
            problems.append(f"effective {key} = {got_e!r}, want {want_n!r}")
    for label, cfg in (("managed", managed), ("effective", effective)):
        entries = get_dotted(cfg, "plugins.entries", {}) or {}
        others = sorted(k for k, v in entries.items() if k != "timely_bot" and isinstance(v, Mapping)
                        and v.get("allow_tool_override"))
        if others:
            problems.append(f"{label} plugins.entries give allow_tool_override to {others} (only timely_bot may)")
    if timely_skills_dir:
        from agent import skill_utils
        clear = getattr(skill_utils, "_external_dirs_cache_clear", None)
        if callable(clear):
            clear()
        dirs = [str(p.resolve()) for p in skill_utils.get_external_skills_dirs()]
        if str(Path(timely_skills_dir).resolve()) not in dirs:
            problems.append(f"skill discovery does not see the Timely skills folder (sees {dirs})")
    return problems
