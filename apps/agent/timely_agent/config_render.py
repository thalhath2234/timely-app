def floor_leaves(floors: Mapping, prefix: str = "") -> dict[str, Any]:
    """Every leaf of a floors dict as ``{"dotted.key": value}``. A non-empty mapping is walked;
    anything else (scalars, lists, empty mappings) is a leaf."""
    out: dict[str, Any] = {}
    for key, value in floors.items():
        dotted = f"{prefix}{key}"
        if isinstance(value, Mapping) and value:
            out.update(floor_leaves(value, dotted + "."))
        else:
            out[dotted] = value
    return out


# The canary checks every leaf of the managed floors after Hermes loaded the files, and the
# managed file's bytes against the floors rendered from values Go passes in ``hello``, so a
# hand-edited managed/config.yaml can neither loosen a floor nor add a key (``command_allowlist``,
# ``terminal.home_mode``) that the floors do not name.
def canary_keys() -> tuple[str, ...]:
    return tuple(floor_leaves(managed_floors(timely_skills_dir=None)))


def deep_merge(base: dict, top: Mapping) -> dict:
    out = copy.deepcopy(base)
    for k, v in top.items():
        if isinstance(v, Mapping) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def get_dotted(cfg: Mapping, dotted: str, default: Any = None) -> Any:
    cur: Any = cfg
    for part in dotted.split("."):
        if not isinstance(cur, Mapping) or part not in cur:
            return default
        cur = cur[part]
    return cur


def dumps(cfg: Mapping) -> bytes:
    return (HEADER + json.dumps(cfg, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def sha256_file(path: os.PathLike | str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_atomic(path: os.PathLike | str, data: bytes, mode: int = 0o600) -> str:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with open(tmp, "wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    try:
        os.chmod(tmp, mode)
    except OSError:
        pass
    os.replace(tmp, path)
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------- MCP entries (sections 6.3, 8.2)

def mcp_entry_hash(entry: Mapping) -> str:
    """sha256 of the entry's canonical JSON (sorted keys, no spaces); Go stores it on approval."""
    return hashlib.sha256(json.dumps(entry, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def private_mcp_url(url: str) -> bool:
    """True for a URL whose host is a literal private, loopback, link-local or CGNAT address
    (or ``localhost``). Go also resolves names before each render; this is the literal check."""
    try:
        host = urlsplit(url).hostname or ""
    except ValueError:
        return True
    if not host:
        return True
    if host.lower() in ("localhost", "localhost.localdomain") or host.lower().endswith(".localhost"):
        return True
    try:
        ip = ipaddress.ip_address(host)
    except ValueError:
        return False
    cgnat = ipaddress.ip_network("100.64.0.0/10")
    return (ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved or ip.is_unspecified
            or ip.is_multicast or (ip.version == 4 and ip in cgnat))


def filter_mcp_servers(servers: Mapping | None, *, host_allowed: bool,
                       approved_hashes: list[str] | tuple[str, ...]) -> tuple[dict, list[str]]:
    """``(kept, dropped_reasons)``. Stdio (``command``) servers only for a host-allowed account
    and only with an approved entry hash; URL servers must not point at a private address."""
    kept: dict[str, Any] = {}
    dropped: list[str] = []
    approved = set(approved_hashes or ())
    for name, entry in (servers or {}).items():
        if not isinstance(entry, Mapping):
            dropped.append(f"{name}: entry is not a mapping")
            continue
        if entry.get("command"):
            if not host_allowed:
                dropped.append(f"{name}: command servers need a host-allowed account")
                continue
            if mcp_entry_hash(entry) not in approved:
                dropped.append(f"{name}: command server was not approved on a host card")
                continue
        elif entry.get("url"):
            if private_mcp_url(str(entry["url"])):
                dropped.append(f"{name}: URL points at a private, loopback or CGNAT address")
                continue
        else:
            dropped.append(f"{name}: needs url or command")
            continue
        kept[str(name)] = dict(entry)
    return kept, dropped


# ---------------------------------------------------------------- renderers

def render_managed(layout, *, timely_skills_dir, browser_executable: str = "") -> tuple[Path, str]:
    floors = managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable)
    path = layout.managed_config
    return path, write_atomic(path, dumps(floors), mode=0o644)


ACCOUNT_STATE = ".timely-account.json"  # what render-account decided; the self-test reads it

# The default SOUL.md (Q-2.6): Timely's identity, named "Timely", replacing Hermes' own ("You are
# Hermes Agent"). Tone only: what the agent may do and the scope rule travel in the Timely block
# Go sends with each run (plan 5.3), so they can differ per account (Q-2.1).
SOUL_TEXT = """You are Timely, the assistant inside the Timely app. You help the person who signed in organize their own work: their tasks, reminders, calendar, projects, docs and sheets.
Be warm, brief and plain-spoken. Answer in the language the person writes in. Prefer one clear next step over a list of options.
Say plainly when something is not possible. Never claim a change was made before Timely confirms it, and never invent facts, IDs or sources.
"""


def account_config(settings: Mapping, *, timely_skills_dir, browser_executable: str = "",
                   workspace: os.PathLike | str | None = None) -> tuple[dict, list[str]]:
    """The account ``config.yaml`` content and the list of dropped MCP entries.

    ``terminal.cwd`` and ``terminal.home_mode`` matter: each run binds Hermes' per-turn terminal
    policy from this file (``run_chat``), and a bound policy ignores ``TERMINAL_*`` in the
    process environment."""
    settings = dict(settings or {})
    cfg: dict[str, Any] = {}
    model = settings.get("model")
    if isinstance(model, Mapping) and model:
        cfg["model"] = {k: v for k, v in model.items() if k in ("default", "provider", "base_url", "api_mode")}
    cfg["toolsets"] = [str(t) for t in settings.get("toolsets") or [] if str(t) not in NEVER_TOOLSETS]
    learning = settings.get("learning") if isinstance(settings.get("learning"), Mapping) else {}
    # Memory and skill writes are decided per write by timely_learning (stage or apply, plan 9b.2),
    # so Hermes' own write_approval gate stays off; flags.learning_writes turns writes off per run.
    cfg["memory"] = {
        "memory_enabled": bool(learning.get("memory", True)),
        "user_profile_enabled": bool(learning.get("user_profile", True)),
        "write_approval": False,
        "memory_char_limit": MEMORY_CHAR_LIMIT,
        "user_char_limit": USER_CHAR_LIMIT,
        "nudge_interval": MEMORY_NUDGE_INTERVAL,
    }
    cfg["skills"] = {
        "disabled": sorted({str(s) for s in settings.get("skills_disabled") or []}),
        "write_approval": False,
        "creation_nudge_interval": SKILL_NUDGE_INTERVAL,
        "ledger": True,
    }
    curator = settings.get("curator")
    curator = curator if isinstance(curator, Mapping) else {"enabled": bool(curator)}
    cfg["curator"] = {
        "enabled": bool(curator.get("enabled", False)),
        "consolidate": False,  # no LLM pass, ever
        "interval_hours": CURATOR_INTERVAL_HOURS,
        "stale_after_days": CURATOR_STALE_AFTER_DAYS,
        # Q-3.6: never auto-archive. auto_archive is accepted only as false.
        "archive_after_days": CURATOR_NEVER_ARCHIVE_DAYS,
        "prune_builtins": False,
    }
    web = settings.get("web") if isinstance(settings.get("web"), Mapping) else {}
    cfg["web"] = {key: (str(web.get(key)) if isinstance(web.get(key), str) and _BACKEND_ID.match(web.get(key))
                        else WEB_BACKEND) for key in ("search_backend", "extract_backend")}
    if settings.get("timezone"):
        cfg["timezone"] = str(settings["timezone"])
    timeout = settings.get("approval_timeout_s")
    cfg["approvals"] = {"timeout": int(timeout) if isinstance(timeout, (int, float)) and timeout > 0 else 600}
    cfg["terminal"] = {"backend": "local", "home_mode": str(settings.get("terminal_home_mode") or "profile")}
    if workspace:
        cfg["terminal"]["cwd"] = str(workspace)
    servers, dropped = filter_mcp_servers(
        settings.get("mcp_servers"), host_allowed=bool(settings.get("host_allowed")),
        approved_hashes=list(settings.get("approved_mcp_hashes") or []))
    cfg["mcp_servers"] = servers
    floors = managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable)
    return deep_merge(cfg, floors), dropped


def render_account(layout, account: str, settings: Mapping, *, timely_skills_dir,
                   browser_executable: str = "") -> dict[str, Any]:
    """Create the account home, write ``config.yaml`` and ``SOUL.md``; returns what Go needs."""
    home = layout.ensure_home(account)
    cfg, dropped = account_config(settings, timely_skills_dir=timely_skills_dir,
                                  browser_executable=browser_executable, workspace=home / "workspace")
    config_sha = write_atomic(home / "config.yaml", dumps(cfg))
    account_state = {"host_allowed": bool(settings.get("host_allowed")),
                     "approved_mcp_hashes": sorted({str(h) for h in settings.get("approved_mcp_hashes") or []}),
                     "config_sha256": config_sha}
    write_atomic(home / ACCOUNT_STATE, (json.dumps(account_state, indent=2, sort_keys=True) + "\n").encode())
    soul = settings.get("soul") if isinstance(settings.get("soul"), str) and settings.get("soul") else SOUL_TEXT
    write_atomic(home / "SOUL.md", soul.encode("utf-8"))
    return {"home": str(home), "config_sha256": config_sha, "mcp_dropped": dropped}


# ---------------------------------------------------------------- canary (needs Hermes imported)

def expected_canary(timely_skills_dir, browser_executable: str = "") -> dict[str, Any]:
    return floor_leaves(managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable))


def _norm(key: str, value: Any) -> Any:
    if key == "skills.external_dirs" and isinstance(value, list):
        return [str(Path(os.path.expandvars(os.path.expanduser(str(v)))).resolve()) for v in value]
    return value


def managed_file_problems(path: os.PathLike | str, timely_skills_dir, browser_executable: str = "",
                          managed_sha256: str | None = None) -> list[str]:
    """The managed file must be exactly the bytes ``render_managed`` writes for these values (and,
    when given, hash to ``managed_sha256``). Any added key, not just a loosened floor, fails."""
    try:
        data = Path(path).read_bytes()
    except OSError as exc:
        return [f"cannot read the managed config: {exc}"]
    problems: list[str] = []
    if managed_sha256 is not None and hashlib.sha256(data).hexdigest() != managed_sha256:
        problems.append("managed config.yaml does not hash to the managed_sha256 prepare reported")
    floors = managed_floors(timely_skills_dir=timely_skills_dir, browser_executable=browser_executable)
    if data != dumps(floors):
        try:
            got = json.loads(data.decode("utf-8").split("\n", 1)[1])
        except (ValueError, IndexError, UnicodeDecodeError):
            got = None
        extra = sorted(set(floor_leaves(got)) - set(floor_leaves(floors))) if isinstance(got, Mapping) else []
        problems.append("managed config.yaml is not the file prepare wrote"
                        + (f" (keys the floors do not have: {extra})" if extra else ""))
    return problems


def canary(timely_skills_dir, browser_executable: str = "", managed_sha256: str | None = None) -> list[str]:
    """Read the managed and effective config back through Hermes; returns the mismatches.

    The managed file must be byte-identical to the floors rendered from ``timely_skills_dir`` and
    ``browser_executable`` (values Go passes in ``hello``, never read from the agent folder), and
    hash to ``managed_sha256`` when given, so an edit to the shared managed file between API start
    and a spawn fails the self-test whatever key it loosens or adds. Every leaf of
    ``managed_floors`` is also compared after Hermes loaded it (``floor_leaves``).

    Checks three readers: the managed file alone (``managed_scope.load_managed_config``), the
    merged config every ``load_config()`` caller sees, and the raw reader skill discovery uses
    (``agent.skill_utils.get_external_skills_dirs``), which must see the Timely skills folder only.
    """
    from hermes_cli import managed_scope
    from hermes_cli.config import load_config

    managed_scope.invalidate_managed_cache()
    problems: list[str] = []
    managed_dir = managed_scope.get_managed_dir()
    if managed_dir is None:
        return ["HERMES_MANAGED_DIR is not a folder Hermes accepts"]
    managed = managed_scope.load_managed_config()
    if not managed:
        return ["Hermes could not read the managed config (missing or malformed)"]
    problems += managed_file_problems(Path(managed_dir) / "config.yaml", timely_skills_dir,
                                      browser_executable, managed_sha256)
    effective = load_config()
    for key, want in expected_canary(timely_skills_dir, browser_executable).items():
        want_n = _norm(key, want)
        got_m = _norm(key, get_dotted(managed, key))
        got_e = _norm(key, get_dotted(effective, key))
        if got_m != want_n:
            problems.append(f"managed {key} = {got_m!r}, want {want_n!r}")
        if got_e != want_n:
            problems.append(f"effective {key} = {got_e!r}, want {want_n!r}")
    for label, cfg in (("managed", managed), ("effective", effective)):
        entries = get_dotted(cfg, "plugins.entries", {}) or {}
        others = sorted(k for k, v in entries.items() if k != "timely_bot" and isinstance(v, Mapping)
                        and v.get("allow_tool_override"))
        if others:
            problems.append(f"{label} plugins.entries give allow_tool_override to {others} (only timely_bot may)")
    if timely_skills_dir:
        from agent import skill_utils
        clear = getattr(skill_utils, "_external_dirs_cache_clear", None)
        if callable(clear):
            clear()
        dirs = [str(p.resolve()) for p in skill_utils.get_external_skills_dirs()]
        if dirs != [str(Path(timely_skills_dir).resolve())]:
            problems.append(f"skill discovery must see only the Timely skills folder (sees {dirs})")
    return problems
