"""Hermes config files for Timely's agent (plan section 6.3). Python owns the shape, Go owns the values.

Three layers:

1. **Managed** (``<agent>/managed/config.yaml`` = ``HERMES_MANAGED_DIR``): host-wide floors,
   written by ``boot.py prepare`` at API start and read back through Hermes' own loader as a
   canary. Hermes deep-merges it on top of every account config (``managed_scope``), so an
   account cannot loosen it through ``load_config()``.
2. **Account** (``<home>/config.yaml``): rendered from the settings JSON Go sends before each
   spawn. It repeats the managed floors, because some Hermes readers take ``config.yaml`` raw
   and never apply the managed overlay (``agent.skill_utils._load_raw_config``, which reads
   ``skills.external_dirs`` and ``skills.disabled``). Its sha256 is the ``settings_hash`` of
   ``hello``; the worker refuses a home whose file no longer matches.
3. **Per run**: model credentials, toolsets and flags arrive in ``run.start``.

Files are written as JSON, which is valid YAML 1.2 and keeps the renderer stdlib-only and the
hash stable. Hermes parses them with its YAML loader (the canary proves it).
"""

